<?php
/**
 * Frontend asset loading.
 *
 * @package Convocept
 * @since   1.0.0
 */

namespace Convocept\Frontend;

use Convocept\EditWindow;
use Convocept\Settings;

defined( 'ABSPATH' ) || exit;

/**
 * Registers and conditionally enqueues the built application.
 *
 * Assets are registered early but only enqueued when a theme integration
 * reports that it actually rendered a comments container, so pages without
 * comments ship no extra JavaScript or CSS.
 *
 * React itself is never bundled: the generated `index.asset.php` lists
 * `wp-element` and friends as dependencies, so the app reuses the copies
 * WordPress core already ships.
 *
 * @since 1.0.0
 */
class Assets {

	/**
	 * Script and style handle shared by the app bundle.
	 *
	 * @since 1.0.0
	 * @var string
	 */
	const HANDLE = 'convocept';

	/**
	 * Settings service.
	 *
	 * @since 1.0.0
	 * @var Settings
	 */
	private $settings;

	/**
	 * Edit window service.
	 *
	 * @since 1.0.0
	 * @var EditWindow
	 */
	private $edit_window;

	/**
	 * Whether a comments container rendered on this request.
	 *
	 * @since 1.0.0
	 * @var bool
	 */
	private $needed = false;

	/**
	 * Constructor.
	 *
	 * @since 1.0.0
	 *
	 * @param Settings   $settings    Settings service.
	 * @param EditWindow $edit_window Edit window service.
	 */
	public function __construct( Settings $settings, EditWindow $edit_window ) {
		$this->settings    = $settings;
		$this->edit_window = $edit_window;
	}

	/**
	 * Register the hooks this service needs.
	 *
	 * @since 1.0.0
	 *
	 * @return void
	 */
	public function register() {
		add_action( 'wp_enqueue_scripts', array( $this, 'register_assets' ) );

		// Late fallback: themes that render comments after wp_enqueue_scripts
		// still get their assets, because footer scripts have not printed yet.
		add_action( 'wp_footer', array( $this, 'maybe_enqueue' ), 1 );
	}

	/**
	 * Flag that the app is needed on this page.
	 *
	 * Called by the theme integrations at the moment they render a mount
	 * point. When the enqueue phase has already passed, the assets are
	 * enqueued immediately rather than waiting for the footer hook.
	 *
	 * @since 1.0.0
	 *
	 * @return void
	 */
	public function need() {
		$this->needed = true;

		if ( did_action( 'wp_enqueue_scripts' ) ) {
			$this->maybe_enqueue();
		}
	}

	/**
	 * Register (but do not enqueue) the script and stylesheet.
	 *
	 * @since 1.0.0
	 *
	 * @return void
	 */
	public function register_assets() {
		$asset_file = CONVOCEPT_DIR . 'build/index.asset.php';

		// Missing build output means the plugin was installed from source
		// without running a build; fail quietly and leave native comments.
		if ( ! is_readable( $asset_file ) ) {
			return;
		}

		// Generated by wp-scripts: core script dependencies and a hash used
		// as the cache-busting version.
		$asset = require $asset_file;

		wp_register_script(
			self::HANDLE,
			CONVOCEPT_URL . 'build/index.js',
			$asset['dependencies'],
			$asset['version'],
			true
		);

		// Lets translators localize the app's strings through WordPress.
		wp_set_script_translations( self::HANDLE, 'convocept' );

		wp_register_style(
			self::HANDLE,
			CONVOCEPT_URL . 'build/style-index.css',
			array(),
			$asset['version']
		);
	}

	/**
	 * Enqueue the registered assets and inline the app configuration.
	 *
	 * Safe to call more than once: it exits early unless the assets are
	 * needed, registered, and not yet enqueued.
	 *
	 * @since 1.0.0
	 *
	 * @return void
	 */
	public function maybe_enqueue() {
		if ( ! $this->needed
			|| wp_script_is( self::HANDLE, 'enqueued' )
			|| ! wp_script_is( self::HANDLE, 'registered' )
		) {
			return;
		}

		wp_enqueue_script( self::HANDLE );

		// Sites styling the app themselves can skip the default stylesheet.
		if ( $this->settings->get( 'load_styles' ) ) {
			wp_enqueue_style( self::HANDLE );
		}

		// Inline rather than a separate request, and 'before' so the config
		// exists by the time the app's own code runs.
		wp_add_inline_script(
			self::HANDLE,
			'window.convoceptConfig = ' . wp_json_encode( $this->config() ) . ';',
			'before'
		);
	}

	/**
	 * Build the configuration object handed to the JavaScript app.
	 *
	 * Mirrors the site's Discussion settings so the app reproduces native
	 * behavior — threading depth, pagination, required fields — instead of
	 * inventing its own rules.
	 *
	 * @since 1.0.0
	 *
	 * @return array Configuration passed to the app as `window.convoceptConfig`.
	 */
	private function config() {
		$post_id = get_queried_object_id();
		$user    = wp_get_current_user();

		return array(
			'postId'  => (int) $post_id,
			'restUrl' => esc_url_raw( rest_url() ),

			// Authenticates REST writes for logged-in users; apiFetch sends
			// it automatically as the X-WP-Nonce header.
			'nonce'    => wp_create_nonce( 'wp_rest' ),
			'settings' => $this->settings->public_subset(),

			// Depth of 1 means core threading is switched off entirely.
			'threadDepth'      => get_option( 'thread_comments' ) ? (int) get_option( 'thread_comments_depth' ) : 1,
			'pageComments'     => (bool) get_option( 'page_comments' ),
			'perPage'          => (int) get_option( 'comments_per_page' ),
			'commentOrder'     => get_option( 'comment_order', 'asc' ),
			'requireNameEmail' => (bool) get_option( 'require_name_email' ),
			'showAvatars'      => (bool) get_option( 'show_avatars' ),
			'cookiesOptIn'     => (bool) get_option( 'show_comments_cookies_opt_in' ),
			'commentsOpen'     => comments_open( $post_id ),
			'mustLogIn'        => (bool) get_option( 'comment_registration' ),
			'loginUrl'         => esc_url_raw( wp_login_url( get_permalink( $post_id ) ) ),

			// Matches the comment_content column limit.
			'maxLength' => 65525,
			'user'      => array(
				'id'          => (int) $user->ID,
				'name'        => $user->ID ? $user->display_name : '',
				'avatar'      => $user->ID ? get_avatar_url( $user->ID, array( 'size' => 48 ) ) : '',
				'canModerate' => current_user_can( 'moderate_comments' ),
			),
		);
	}
}
